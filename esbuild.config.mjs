import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import postcss from "esbuild-postcss";
import { logBuildError } from "./scripts/learning/error-logger.mjs";
import { packedLocales } from "./scripts/esbuild-packed-locales.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
  banner: {
    js: banner,
  },
  entryPoints: ["main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtinModules,
  ],
  format: "cjs",
  target: "es2018",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  outfile: "main.js",
  minify: prod,
  // Translations are bundled; \uXXXX escapes would triple non-Latin text
  charset: "utf8",
  // Only main.js ships: images are inlined as data: URLs, locales packed
  loader: { ".png": "dataurl", ".webp": "dataurl" },
  plugins: [packedLocales()],
});

if (prod) {
  try {
    await context.rebuild();
    process.exit(0);
  } catch (error) {
    console.error("✗ esbuild failed:", error.message);
    await logBuildError({
      script: "esbuild.config.mjs",
      error: error,
      context: { mode: "production" },
    });
    process.exit(1);
  }
} else {
  try {
    await context.watch();
  } catch (error) {
    console.error("✗ esbuild watch failed:", error.message);
    await logBuildError({
      script: "esbuild.config.mjs",
      error: error,
      context: { mode: "development" },
    });
    process.exit(1);
  }
}
